def read_solutions(document, pages):
    tasks = {}
    current = None
    for page_index in pages:
        for line in document[page_index].get_text().splitlines():
            line = line.strip()
            match = TASK_HEADER.match(line)
            if match:
                current = int(match[1])
                if current in tasks:
                    raise ValueError(f'Duplicate task {current} on page {page_index + 1}')
                tasks[current] = []
                line = line[match.end():]
            if (not line or line.startswith(('Решения задач', 'Задачи на'))
                    or line.isdigit() or line == 'W' or current is None):
                continue
            tasks[current].append(line)
    return tasks


def normalize_lines(lines):
    # A discretionary hyphen disappears when the printed line joins the next.
    # Some older PDFs represent these hyphens as a literal dash.
    text = '\n'.join(lines)
    text = re.sub(r'(?<=[А-Яа-яЁё])(?:-|\u00ad)\n(?=[А-Яа-яЁё])', '', text)
    text = ' '.join(text.replace('\u00ad', '').split())
    text = re.sub(r'= =', '=', text)
    text = re.sub(r'\b([см]+)2\b', r'\1²', text)
    return text


def parse_steps(year, number, lines):
    if number in OVERRIDES.get(year, {}):
        return OVERRIDES[year][number]
    if (year, number) == (2022, 28):
        return [normalize_lines([line]) for line in lines]
    text = normalize_lines(lines)
    steps = STEP_BOUNDARY.split(text)
    if not text:
        raise ValueError(f'{year}, task {number}: missing explanation')
    return steps


def save_figure(document, year, number, index, figure):
    page, coordinates, _ = figure
    bounds = fitz.Rect(coordinates)
    relative_path = ASSET_PATH / str(year) / f'task-{number:02d}-{index}.svg'
    destination = DIST / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(cropped_svg(document, page, bounds), encoding='utf-8')
    # The lesson uses these dimensions to lay out the figure and calculations together.
    return {'image': relative_path.as_posix(), 'imageWidth': round(bounds.width * 3),
            'imageHeight': round(bounds.height * 3)}


