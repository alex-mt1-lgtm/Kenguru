def build_edition(year, document, tasks):
    entries = {}
    for number, lines in tasks.items():
        if (year, number) == (2023, 29):
            entries[number] = {'steps': labyrinth_2023()}
            continue
        steps = [{'text': text} for text in parse_steps(year, number, lines)]
        for index, figure in reversed(list(enumerate(FIGURES.get(year, {}).get(number, []), 1))):
            image = save_figure(document, year, number, index, figure)
            step = steps[min(figure[2], len(steps) - 1)]
            if 'image' in step:
                steps.insert(steps.index(step), {'text': 'Рассмотрим рисунок из официального решения.', **image})
            else:
                step.update(image)
        entries[number] = {'steps': steps}
    return entries


def build():
    source = ROOT / 'sources' / '2021' / 'solutions.pdf'
    with fitz.open(source) as document:
        editions = {2021: build_edition(2021, document, dict.fromkeys(range(1, 25)))}
    for year, pages in PAGE_RANGES.items():
        source = ROOT / 'sources' / str(year) / 'solutions.pdf'
        with fitz.open(source) as document:
            tasks = read_solutions(document, pages)
            if list(tasks) != list(range(1, 31)):
                raise ValueError(f'{year}: unexpected task numbers {list(tasks)}')
            editions[year] = build_edition(year, document, tasks)
    encoded = json.dumps(editions, ensure_ascii=False, separators=(',', ':'))
    (DIST / 'years' / 'grade-solution-steps.js').write_text(
        "'use strict';\n// Generated by scripts/build-grade-solution-steps.py.\n"
        "globalThis.KENGURU_GRADE_SOLUTION_STEPS = " + encoded + ";\n", encoding='utf-8',
    )


if __name__ == '__main__':
    build()
