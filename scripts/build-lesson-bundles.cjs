'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {defaultScripts, dist, loadLessonCatalog, readScript, yearFile} = require('./lesson-catalog.cjs');

const {readingPdfFor} = require('./reading-pdf.cjs');
const output = path.join(dist, 'editions');
const header = '// Generated by scripts/build-lesson-bundles.cjs.\n';
const byYear = (mapping, year) => mapping?.[year] === undefined ? {} : {[year]: mapping[year]};
const byEdition = (mapping, id) => Object.fromEntries(Object.entries(mapping).filter(([key]) => key.startsWith(id + '/')));
const assign = (name, value) => `globalThis.${name} = ${JSON.stringify(value)};`;
const script = name => readScript(yearFile(name));

function createBundle(entry, model) {
  const {id, year} = entry;
  const {context, choiceLayouts, graphicAnswerDescriptions} = model;
  const layouts = byEdition(choiceLayouts, id);
  const descriptions = byEdition(graphicAnswerDescriptions, id);
  const content = [assign('KENGURU_CHOICE_LAYOUTS', layouts)];
  const broadArchive = id.endsWith('-3-4');
  const general = [...context.KENGURU_GRADES_7_8, ...context.KENGURU_JUNIOR_SENIOR, ...model.completedMath].find(edition => edition.id === id);
  const middle = context.KENGURU_GRADES_5_6.find(edition => edition.id === id);
  let selection = `(globalThis.KENGURU_ARCHIVE[${JSON.stringify(id)}] ?? [].concat(globalThis.KENGURU_ARCHIVE[${year}] ?? []).find(edition => edition.id === ${JSON.stringify(id)}))`;
  if (id === '2024-3-4') {
    content.push(...defaultScripts.map(readScript));
    const {id, year, grades, label, sources} = entry;
    selection = `({
      ...${JSON.stringify({id, year, grades, label, sources})},
      lessons: [...LESSONS, ...FOUR_POINT_LESSONS, ...FIVE_POINT_LESSONS].map((lesson, i) => ({
        ...lesson, points: lesson.points ?? 3,
        originalImage: lesson.originalImage ?? (\`assets/original-\${i + 1}.png\`),
      })),
      scenes: [...Array(8).fill(null), ...FOUR_POINT_SCENES, ...FIVE_POINT_SCENES],
      fruitPuzzle: {fruits: FOUR_FRUITS, icons: FOUR_FRUIT_ICONS, people: FOUR_FRUIT_PEOPLE, preferences: FOUR_FRUIT_PREFS},
    })`;
  } else if (model.subjectRows.has(id)) {
    const {meta, rows} = model.subjectRows.get(id);
    content.push(readScript('contests/subject-edition.js'));
    selection = `globalThis.makeSubjectEdition(${JSON.stringify(meta)}, ${JSON.stringify(rows)})`;
  } else if (model.russianRows.has(id)) {
    content.push(readScript('contests/medvezhonok-archive.js'));
    const grade = entry.grades.join('-');
    const material = model.russianMaterials.find(row => row.year === year && row.grade === grade);
    const extra = material ? ', ' + JSON.stringify(material) : '';
    selection = `globalThis.makeMedvezhonokEdition(${year}, ${JSON.stringify(grade)}, ${JSON.stringify(model.russianRows.get(id))}${extra})`;
  } else if (entry.subject === 'ru') {
    content.push(readScript('contests/medvezhonok-2025.js'));
    selection = `globalThis.MEDVEZHONOK_EDITIONS.find(edition => edition.id === ${JSON.stringify(id)})`;
  } else if (general) {
    content.push(assign('KENGURU_GRADES_7_8', [general]), script('grade-editions'));
  } else if (middle) {
    content.push(assign('KENGURU_GRADES_5_6', [middle]));
    for (const name of ['KENGURU_GRADE_CONDITIONS', 'KENGURU_GRADE_SOLUTION_STEPS', 'KENGURU_GRADE_KEYS', 'KENGURU_GRADE_TITLES']) {
      content.push(assign(name, byYear(context[name], year)));
    }
    if (year === 2000) content.push(script('visual-2000-five-six'));
    if (year === 2024 || year === 2026) {
      for (const points of ['three', 'four', 'five']) content.push(script(`visual-${year}-${points}`));
    }
    content.push(script('grades-5-6'));
  } else if (broadArchive && year === 2000) {
    content.push(...['2000-visual', '2000-three', '2000-four', '2000-five', '2000'].map(script));
  } else if (broadArchive && [2020, 2021, 2022, 2023, 2025, 2026].includes(year)) {
    if (year === 2026) content.push(assign('KENGURU_2026_CONDITION_ART', context.KENGURU_2026_CONDITION_ART));
    content.push(script(String(year)));
  } else if (broadArchive) {
    content.push(assign('KENGURU_LEGACY', context.KENGURU_LEGACY.filter(record => record[0] === year)),
      assign('KENGURU_LEGACY_CONDITIONS', byYear(context.KENGURU_LEGACY_CONDITIONS, year)), script('legacy-editions'));
  } else {
    throw new Error(`Unknown edition source: ${id}`);
  }
  const readers = {};
  for (const field of ['tasksUrl', 'answersUrl', 'solutionUrl']) {
    const url = readingPdfFor(entry.sources[field]);
    if (url) readers[field] = url;
  }
  if (general?.reviewedKey) content.push(`${selection}.sources.reviewedKey = true;`);
  let registration = selection;
  if (Object.keys(readers).length) {
    content.push(`const edition = ${selection};\nedition.sources.readers = ${JSON.stringify(readers)};`);
    registration = 'edition';
  }
  const bundle = `${header}((globalThis, register) => {\n'use strict';\n${content.join('\n')}\nregister(${registration}, globalThis.KENGURU_CHOICE_LAYOUTS, ${JSON.stringify(descriptions)});\n})({KenguruVisual: globalThis.KenguruVisual}, globalThis.KenguruEditions.register);\n`;
  const check = vm.createContext({KenguruVisual: context.KenguruVisual, KenguruEditions: {
    register(edition, choiceLayouts) {
      assert.equal(edition.id, id);
      assert.equal(edition.scenes.length, entry.indices.length);
      const own = edition.lessons.map((lesson, index) => {
        const number = lesson.number ?? index + 1;
        const layout = choiceLayouts[id + '/' + number];
        return {...lesson, number, year, datasetId: id, ...(layout ? {
          choiceLayout: layout, conditionImage: layout.condition?.src,
          choices: layout.options.map(option => option.text ?? ''), choiceImages: layout.options.map(option => option.image),
        } : {})};
      });
      assert.deepEqual(JSON.parse(JSON.stringify(own)), JSON.parse(JSON.stringify(entry.indices.map(index => model.lessons[index]))), id);
    },
  }});
  vm.runInContext(bundle, check, {filename: id + '.js'});
  return bundle;
}

function build(check) {
  const model = loadLessonCatalog();
  const index = model.catalog.map(entry => [entry.id, entry.year, entry.grades, entry.label,
    entry.indices.map(index => model.lessons[index].number),
    entry.indices.map(index => Number.isInteger(model.lessons[index].numericAnswer ?? model.lessons[index].answer) ? model.lessons[index].points : '.').join(''),
    ...(entry.subject ? [entry.subject] : []),
  ]);
  function write(file, contents) {
    const target = path.join(output, file);
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) {
        throw new Error(`Run node scripts/build-lesson-bundles.cjs to update ${file}`);
      }
    } else fs.writeFileSync(target, contents);
  }
  if (!check) fs.mkdirSync(output, {recursive: true});
  for (const entry of model.catalog) write(entry.id + '.js', createBundle(entry, model));
  write('index.js', `${header}globalThis.KENGURU_EDITION_INDEX = ${JSON.stringify(index)};\n`);
}

build(process.argv.includes('--check'));
