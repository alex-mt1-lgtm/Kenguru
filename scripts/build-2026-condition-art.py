# Two lines of neighboring prose enter the bounding box of the circular figure.
PROSE_OVERLAPS = {19: [(308.5, 22, 334.5, 33), (308.5, 108.3, 352.4, 113)]}


def render(page, region, masks=()):
    pixmap = page.get_pixmap(matrix=fitz.Matrix(SCALE, SCALE), clip=fitz.Rect(region), alpha=False)
    image = Image.frombytes('RGB', (pixmap.width, pixmap.height), pixmap.samples)
    if masks:
        draw = ImageDraw.Draw(image)
        for x0, y0, x1, y1 in masks:
            draw.rectangle((round(x0 * SCALE) - pixmap.x, round(y0 * SCALE) - pixmap.y,
                            round(x1 * SCALE) - pixmap.x, round(y1 * SCALE) - pixmap.y),
                           fill='white')
    return image


def combine(frames, direction, padding):
    gap = padding * SCALE
    if direction == 'row':
        height = max(frame.height for frame in frames)
        width = sum(frame.width for frame in frames) + gap * (len(frames) - 1)
        canvas = Image.new('RGB', (width, height), 'white')
        offset = 0
        for frame in frames:
            canvas.paste(frame, (offset, (height - frame.height) // 2))
            offset += frame.width + gap
    else:
        width = max(frame.width for frame in frames)
        height = sum(frame.height for frame in frames) + gap * (len(frames) - 1)
        canvas = Image.new('RGB', (width, height), 'white')
        offset = 0
        for frame in frames:
            canvas.paste(frame, ((width - frame.width) // 2, offset))
            offset += frame.height + gap
    return canvas


def save(image, filename):
    relative = ASSETS / (filename + '.png')
    image.save(DIST / relative, optimize=True)
    return relative.as_posix()


def build():
    entries = {}
    with fitz.open(ROOT / 'sources' / '2026' / 'tasks.pdf') as document:
        for number, (page, region) in FIGURES.items():
            entries[number] = render(document[page], region, PROSE_OVERLAPS.get(number, ()))
        for number, (page, direction, gap, regions) in FRAGMENTS.items():
            frames = [render(document[page], region) for region in regions]
            entries[number] = combine(frames, direction, gap)
        if sorted(entries) != list(range(2, 25)):
            raise ValueError(f'Unexpected task numbers: {sorted(entries)}')
        data = {}
        for number, image in sorted(entries.items()):
            data[number] = {
                'image': save(image, f'condition-{number}'),
                'width': image.width,
                'height': image.height,
            }
        save(render(document[3], FRAGMENTS[20][3][0]), 'condition-20-cards')
        data[21]['choiceImages'] = [
            save(render(document[3], region), f'condition-21-choice-{index}')
            for index, region in enumerate(STICK_CHOICES)
        ]
    encoded = json.dumps(data, separators=(',', ':'))
    (DIST / 'years' / '2026-condition-art.js').write_text(
        "'use strict';\n// Generated by scripts/build-2026-condition-art.py.\n"
        "globalThis.KENGURU_2026_CONDITION_ART = " + encoded + ";\n", encoding='utf-8',
    )


if __name__ == '__main__':
    build()
