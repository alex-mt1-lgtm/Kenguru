'use strict';

const fs = require('node:fs');
const path = require('node:path');
const {loadLessonCatalog} = require('./lesson-catalog.cjs');

const destination = path.join(__dirname, '..', 'dist', 'years', 'archive-formats.js');

function buildArchiveFormats() {
  const {lessons} = loadLessonCatalog();
  const editions = new Map();
  for (const lesson of lessons) {
    const formats = editions.get(lesson.datasetId) ?? new Set();
    formats.add(lesson.paperEdition && lesson.steps.length === 2 ? 'key' : 'walkthrough');
    editions.set(lesson.datasetId, formats);
  }
  const data = Object.fromEntries([...editions].sort(([a], [b]) => a.localeCompare(b)).map(([edition, formats]) =>
    [edition, formats.size > 1 ? 'mixed' : [...formats][0]]
  ));
  return "'use strict';\n// Generated by scripts/build-archive-formats.cjs.\n" +
    'globalThis.KENGURU_ARCHIVE_FORMATS = ' + JSON.stringify(data) + ';\n';
}

module.exports = {buildArchiveFormats};

if (require.main === module) {
  const expected = buildArchiveFormats();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== expected) {
      throw new Error('Run node scripts/build-archive-formats.cjs to update the archive format labels');
    }
  } else {
    fs.writeFileSync(destination, expected);
  }
}
